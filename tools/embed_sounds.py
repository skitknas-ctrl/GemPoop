"""Bakar in ljudfilerna i sounds/ i index.html (mellan GEMPOOP_SOUNDS-markörerna).

Kör från repots rot:  python3 tools/embed_sounds.py
Filnamn: fart_*.ogg (apornas prutt), slurp_*.ogg (grodornas slurp), sax*.ogg (avklippt tunga).
"""
import base64, glob, json, os, re

groups = {'fart': 'fart*.ogg', 'slurp': 'slurp*.ogg', 'snip': 'sax*.ogg'}
data = {}
for name, pattern in groups.items():
    files = sorted(glob.glob(os.path.join('sounds', pattern)))
    data[name] = [base64.b64encode(open(f, 'rb').read()).decode('ascii') for f in files]
    print(name, [os.path.basename(f) for f in files])

block = ('<script id="gempoop-sounds">/* GEMPOOP_SOUNDS start: generated by tools/embed_sounds.py */\n'
         'window.GEMPOOP_SOUNDS = ' + json.dumps(data) + ';\n/* GEMPOOP_SOUNDS end */</script>')
html = open('index.html', encoding='utf-8').read()
pat = re.compile(r'<script id="gempoop-sounds">.*?</script>', re.S)
if pat.search(html):
    html = pat.sub(lambda m: block, html)
else:
    html = html.replace('<script>\n"use strict";', block + '\n<script>\n"use strict";', 1)
open('index.html', 'w', encoding='utf-8').write(html)
